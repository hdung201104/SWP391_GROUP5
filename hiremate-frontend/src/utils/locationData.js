/**
 * Ghép xã/phường, quận/huyện và tỉnh/thành thành chuỗi địa chỉ hoàn chỉnh chuẩn Việt Nam
 */
export const formatFullAddress = (ward, district, province) => {
  const parts = [];
  if (ward && ward !== 'Toàn khu vực' && !ward.includes('khác')) parts.push(ward.trim());
  if (district && district !== 'Toàn khu vực' && !district.includes('khác')) parts.push(district.trim());
  if (province && province !== 'Tỉnh / Thành khác') parts.push(province.trim());
  return parts.length > 0 ? parts.join(', ') : (province || 'Việt Nam');
};

export const formatLocation = (district, province) => formatFullAddress('', district, province);
